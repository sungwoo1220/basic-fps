'use strict';
// The existing authoritative rules are the source of truth; no manually copied map constants.
const fs=require('fs'),path=require('path');
const {arena,characterParts,weapon,move}=require('../game/public/shared.js');
const output=path.join(__dirname,'../unreal/Source/BasicFPS/Public/GeneratedRules.h');
const numbers=object=>Object.values(object).map(value=>String(value)).join(', ');
const scenarios=[];
for(const seed of [1,7,42,299,999,123456]){
  let random=seed>>>0;
  const state={x:-17,z:-17,vx:0,vz:0};
  for(let step=0;step<1200;step++){
    random=(Math.imul(random,1664525)+1013904223)>>>0;
    move(state,{keys:(random>>>24)&47,yaw:(random/4294967296)*Math.PI*2-Math.PI});
  }
  scenarios.push(`    {${seed}u, ${numbers(state)}}`);
}
const text=`// Generated by scripts/export-unreal-rules.cjs. Edit game/public/shared.js instead.
#pragma once
#include <array>
namespace BasicFPS {
struct Box { double x,z,w,d,h; };
inline constexpr std::array<Box,${arena.boxes.length}> Boxes = {{
${arena.boxes.map(box=>'    {'+numbers(box)+'}').join(',\n')}
}};
struct Part { double x,y,z,w,h,d,damage; };
inline constexpr std::array<Part,${characterParts.length}> Parts = {{
${characterParts.map(part=>'    {'+numbers(part)+'}').join(',\n')}
}};
inline constexpr double Step=${arena.step}, Radius=${arena.radius}, Speed=${arena.speed}, WalkSpeed=${arena.walkSpeed}, Acceleration=${arena.acceleration}, Deceleration=${arena.deceleration};
inline constexpr double ShotInterval=${weapon.interval/1000}, BloomPerShot=${weapon.bloomPerShot}, MaxBloom=${weapon.maxBloom};
struct Golden { unsigned int seed; double x,z,vx,vz; };
inline constexpr std::array<Golden,${scenarios.length}> GoldenCases = {{
${scenarios.join(',\n')}
}};
}
`;
if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==text)throw Error('Unreal rules are stale. Run node scripts/export-unreal-rules.cjs.');
}else{
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output,text);
}
